-- ✅ الشبكة سليمة (وصلنا للسيرفر ورجعلنا رد Postgres).
--
-- ⚠️ تصحيح: رسالة `user "postgres"` **طبيعية** — الـpooler بيقسّم
--    postgres.rxtjoqulmgkkcohmgzgi لمستخدم + مشروع، وبيبلّغ عن الأول بس.
--    فهي مش دليل على مشكلة في الخريطة. المشكلة في الباسورد.
--
-- السبب الأرجح: باسورد Supabase المولّد بيحتوي رموز (مسافة أو = أو '
--    أو \). صيغة conninfo بتفصل الحقول بالمسافات، فأي رمز من دول
--    بيقطع القيمة والباقي يتفسّر كحقل تاني — والنتيجة «باسورد غلط».
--    الحل: نحطه بين علامتَي تنصيص مفردة جوه الـconninfo.
--
-- ⚠️ في SQL، '' جوه نص = علامة تنصيص واحدة. فالشكل النهائي:
--       password=''الباسورد''
--    يعني حط الباسورد بين **علامتين مزدوجتين من النوع المفرد** زي تحت.
--
-- ⚠️ لو الباسورد نفسه فيه ' أو \ — ارجع اعمل Reset وخد واحد
--    **حروف وأرقام بس**، وحدّث n8n بيه. أسهل من أي هروب.
-- ═══════════════════════════════════════════════════════════════════

create extension if not exists dblink;

-- ── اختبار 1: الباسورد بين علامتَي تنصيص (الأرجح إنه ينجح) ────────
select 'مع تنصيص' as المحاولة, *
from dblink(
  'host=aws-0-eu-west-1.pooler.supabase.com port=5432 dbname=postgres '
  || 'user=postgres.rxtjoqulmgkkcohmgzgi sslmode=require '
  || 'password=''حط-الباسورد-هنا''',
  'select count(*) from public.branches'
) as t(عدد_الفروع bigint);


