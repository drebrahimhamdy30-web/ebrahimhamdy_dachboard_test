/* ============================================================
   بند «الإجماليات ونسخ الحركات»: الـselector يشمل الملخّص فقط
   ------------------------------------------------------------
   كان '.sumcard, .chips'. بعد ما المالك طلب إظهار **فلتر القنوات**
   لغير المصرَّح له (الفلتر أداة فرز، واللي بيتحجب هو مبلغ كل قناة
   مش وجودها)، صف القنوات طلع برّه كارت الملخّص وبقى ظاهر للكل.

   الـselector ده بيستعمله Session.guardTabs — وهي **مش متنادية في
   الشاشة دي** حاليًا، فالقيمة القديمة كانت خاملة. بنصلّحها عشان لو
   اتنادت بعدين ما تخفيش الفلتر عن اللي من حقه يشوفه.
   ============================================================ */
update public.app_page_tabs
   set selector = '.sumcard'
 where page_key = 'current_shift' and tab_key = 'totals';
