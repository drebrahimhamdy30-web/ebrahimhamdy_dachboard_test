-- لون ملاحظات التحويل من إعدادات المؤسسة            (2026-10-17)
--
-- شاشة «تحويلات الفروع» كانت بتعرض ملاحظة الطلب (زي «مطلوب لقرب
-- انتهاء الصلاحية» و«تحويل للأهمية القصوى») بـvar(--danger) — أحمر
-- ثابت في الكود. المالك شايف إن الأحمر مش مناسب وعايز التحكم يبقى
-- من إعدادات المؤسسة زي باقي ألوان الهوية.
--
-- ملاحظة: شاشتَي «خدمة العملاء» و«المشتريات» بتعرضا نفس نوع الملاحظة
-- بـvar(--accent-dark) (لون الهوية) أصلًا — يعني transfers كانت
-- الشاذة. العمود ده بيدّي تحكم صريح بدل ما يبقى مربوط بلون الهوية.
--
-- القيمة الفاضية مقصودة: الشاشة بتستعمل
--   var(--note-color, var(--accent-dark))
-- فلو الإعداد مش متظبط، اللون بيرجع للون الهوية — مش بيختفي ولا
-- بيرجع أحمر.
-- ═══════════════════════════════════════════════════════════════════

alter table public.org_settings
  add column if not exists brand_note text;

comment on column public.org_settings.brand_note is
  'لون ملاحظات التحويل في شاشة تحويلات الفروع (hex). فاضي = يستعمل لون الهوية الغامق.';

notify pgrst, 'reload schema';

-- الفحص
select id, company_name, brand_primary, brand_primary_dark, brand_note
  from public.org_settings where id = 1;
