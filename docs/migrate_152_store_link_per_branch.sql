/* ═══════════════════════════════════════════════════════════════════
   رابط مورّد لكل فرع بدل رابط واحد لكل الفروع
   ═══════════════════════════════════════════════════════════════════
   ── الطلب (المالك) ──────────────────────────────────────────────
   «ابن سينا وفارما رابط لكل فرع مش رابط لكل الفروع زي باقي المخازن.»

   السبب العملي: المخزنين دول الطلب عندهم **أونلاين بحساب لكل صيدلية**
   (ابن سينا 3 حسابات، وفارما بورتال لكل فرع) — مش مندوب بياخد قائمة
   واحدة ويقسّمها. فالرابط المجمّع بيحمّل الموظف تقسيمة هو مش محتاجها.

   ── ليه علم في الجدول مش شرط في الكود ──────────────────────────
   حطّ الاسمين في JS معناها إن أي تغيير (مخزن جديد يشتغل أونلاين،
   أو واحد منهم يرجع لمندوب) محتاج نشر كود. العلم على `stores`
   بيخلّيها إعداد يتغيّر من القاعدة.

   ⚠️ `supplier_link_create` **مش محتاجة أي تعديل** — بتقبل `p_branch`
      من الأول، وكانت الشاشة بتبعت null دايمًا. اللي اتغيّر إن الشاشة
      بقت تنادي مرة لكل فرع فيه أصناف.

   يتطبّق على: السحابة **و** السيرفر الذاتي.
   ═══════════════════════════════════════════════════════════════════ */

alter table public.stores
  add column if not exists link_per_branch boolean not null default false;

comment on column public.stores.link_per_branch is
  'true = رابط منفصل لكل فرع (المخازن اللي الطلب عندها أونلاين بحساب لكل صيدلية). false = رابط واحد بتبويبات.';

update public.stores
   set link_per_branch = true
 where name in ('ابن سينا', 'فارما اوفر سيز');
