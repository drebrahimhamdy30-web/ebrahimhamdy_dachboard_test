/* ════════════════════════════════════════════════════════════════
   «تعاقد بغير عقد» في فواتير التعاقد   (2026-10-30)
   ----------------------------------------------------------------
   **ليه**: المالك بيلاقي في شاشة فواتير التعاقد عملاء مش متعاقدين
   («احمد ماهر لطفى» وغيره). رجعنا للمصدر: في eplus الفواتير دي
   عليها `sth_contract=1` بس `fh_contract_id=0` و`fh_company_part=0`
   — يعني الكاشير داس زرار «تعاقد» من غير ما يختار العقد. مش عيب
   في المزامنة؛ المزامنة بتاخد أي حاجة علامتها تعاقد وبتنقلها أمينة.

   الحجم: ١٨ فاتورة من ١ مايو لـ٢٩ أكتوبر (٣٬٤٣٢ ج)، ٨ منهم من غير
   عميل أصلًا. والمحاسب كان بيلغيها **بإيده** كل مرة — ٢٦ من ٣٦
   حالتهم «ملغاة» دلوقتي. ده شغل يدوي متكرر على غلط معروف مصدره.

   **ليه عمود محسوب مش عمود بتملاه المزامنة**: `fh_contract_id` مش
   موجود في اللي n8n بيجيبه، والوركفلو مش تحت إيدينا هنا. لكن الأثر
   باين في بيانات عندنا بالفعل: `total_bill_net` = حصة العميل.
   العقود الحقيقية حصة العميل فيها 0% (مساهمة كاملة) أو 25% (3/4)
   أو 50% — قِسنا التوزيع على ١٨٤٦ فاتورة وطلع ثنائي القمة بوضوح:
   0–33% (العقود الحقيقية) مقابل 90–100% (دي). فعمود `generated`
   بيحسب نفسه على كل صف، بما فيهم صفوف n8n الجاية — **من غير ما
   نلمس الوركفلو خالص**.

   ⚠️ السقف `net <= total` مش تجميل: قيمة فاتورة التعاقد **بتتجمّد**
      بعد أول أكشن (راجع ذاكرة contract-invoice-value-freeze)، فصف
      قديم ممكن يبقى total أقل من net ونسبته تطلع 221%. من غير السقف
      ده كان هيتعلّم صف عليه **مطالبة فعلًا** ويختفي من قايمة
      المحاسب. بعد التشديد: ٣٦ صف متعلّم، **صفر** منهم عليه مطالبة.

   في الشاشة: شريحة «⚠️ تعاقد بغير عقد» + علامة حمرا على الصف،
   و**بتتشال من «قيد المتابعة»** عشان ماتستهلكش وقت المحاسب — لكن
   بتفضل ظاهرة في «الكل» وفي شريحتها، فغلط الكاشير مايتخبّاش.

   يتطبّق على: السحابة (اتعمل 2026-10-30) **و** السيرفر الذاتي.
   ════════════════════════════════════════════════════════════════ */

drop index if exists public.ix_contract_invoices_no_contract;
alter table public.contract_invoices drop column if exists no_contract;

alter table public.contract_invoices
  add column no_contract boolean
  generated always as (
    total_bill > 0
    and total_bill_net is not null
    and total_bill_net >= 0.85 * total_bill
    and total_bill_net <= total_bill
  ) stored;

comment on column public.contract_invoices.no_contract is
  'تعاقد بغير عقد: الكاشير داس «تعاقد» من غير ما يختار العقد، فالعميل دفع كل القيمة';

create index ix_contract_invoices_no_contract
  on public.contract_invoices (no_contract) where no_contract;
