/* ============================================================
   صلاحيات الصفحات: قيد يمنع التكرار
   ------------------------------------------------------------
   اتكشفت لما المالك بعت صورة القائمة ولقى **«حساب فرع السيوف» ظاهرة
   مرتين**. السبب: `page_permissions` مافيهوش قيد فريد على
   (page_key, role)، فصفوف الصلاحية اتضافت مرتين والقائمة — اللي
   بتربط الصفحات بالصلاحيات — عرضت الصفحة مرة لكل صف.

   seyouf_finance كان مكرر في **٩ أدوار** (كل أدواره).

   ⚠️ والأخطر إن `insert ... on conflict do nothing` **مش بيحمي من
   حاجة** من غير قيد: من غير هدف تعارض مفيش تعارض يحصل أصلًا، فأي
   ترحيل يتشغّل مرتين بيضاعف الصفوف بصمت. ده ينطبق على كل الترحيلات
   اللي بتضيف صلاحيات — ومنها migrate_148 بتاع شاشة visa.

   الإصلاح: تنظيف المكرر + قيد فريد يخلّي `on conflict` يشتغل فعلًا.
   ============================================================ */

/* ١) تنظيف: نسيب أقدم صف لكل (صفحة، دور) */
delete from public.page_permissions a
 using public.page_permissions b
 where a.page_key = b.page_key
   and a.role     = b.role
   and a.ctid     > b.ctid;

/* ٢) القيد — من دلوقتي `on conflict do nothing` بيمنع التكرار فعلًا */
create unique index if not exists ux_page_permissions_key_role
  on public.page_permissions (page_key, role);
