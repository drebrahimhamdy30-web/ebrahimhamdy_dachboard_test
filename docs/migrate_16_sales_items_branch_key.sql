-- ═══════════════════════════════════════════════════════════════════
--  migrate_16 — الفرع يدخل في مفتاح sales_items
-- ═══════════════════════════════════════════════════════════════════
--  ⚠️ مش مستعجل. اتكتب 2026-09-16 عشان مايتنساش، ويتطبّق في وقت هادي.
--
--  المشكلة:
--    القيد الحالي  UNIQUE (bill_no, line_no)  — من غير الفرع.
--    ووركفلو n8n بيعمل  ON CONFLICT (bill_no, line_no) DO UPDATE.
--
--    يعني لو فرعين طلّعوا نفس رقم الفاتورة، التاني **بيكتب فوق** الأول
--    من غير أي خطأ.
--
--  ليه شغّال دلوقتي:
--    صدفة مش تصميم. كل فرع عدّاده في نطاق مختلف:
--      سيدى بشر     (ابراهيم حمدي 3)  5 خانات   12,165 →    24,218
--      سان ستيفانو  (ابراهيم حمدي 2)  6 خانات  190,371 →   203,093
--      المعمورة     (الصيدلية)         7 خانات 1,422,796 → 1,464,002
--
--  إمتى هيتكسر (بمعدلات 2026-07-27 → 2026-09-16):
--    سيدى بشر 240 فاتورة/يوم، ومحتاج يوصل 190,371 (أقدم فاتورة سان
--    ستيفانو في الجدول):
--        (190,371 − 24,218) ÷ 240 = 692 يوم  ≈  منتصف 2028
--    ساعتها كل فاتورة جديدة لسيدى بشر هتمسح فاتورة قديمة لسان ستيفانو
--    بنفس الرقم، والتقارير التاريخية تتحوّل بصمت.
--    (سان ستيفانو → المعمورة محتاج 13 سنة — مش خطر.)
--
--  اللي اتفحص قبل كتابة الملف:
--    ✅ store_name: صفر NULL وصفر فاضي من 134,830 صف
--       (مهم: القيد الفريد بيعتبر NULL ≠ NULL، فصف NULL مش هيتحمى)
--    ✅ 13 دالة بتقرا sales_items، ولا واحدة بتعمل ON CONFLICT
--    ✅ الكتابة الوحيدة من الشاشات: reports.html «تمت مراجعة السعر»
--       .update().eq('id') — بالمفتاح الأساسي، مش متأثرة بالتغيير
--    ✅ reports.html أصلاً بيقرا بـ .eq('store_name').eq('bill_no') —
--       الشاشة بتعتبر (المخزن + الفاتورة) هوية، والقيد الجديد بيطابقها
--    ✅ نود n8n بـ mappingMode "defineBelow" — price_reviewed* مش في
--       القايمة، فالمزامنة مابتمسحش حالة المراجعة
--
--  ⚠️⚠️ الترتيب إلزامي — القيد والوركفلو لازم يفضلوا متطابقين في كل لحظة:
--
--     ON CONFLICT (a,b) في بوستجرس **لازم** يلاقي قيد فريد على (a,b) بالظبط.
--     لو شلت القيد القديم والوركفلو لسه بيقول (bill_no, line_no)
--     → كل upsert هيفشل  → المبيعات تقف.
--
--     عشان كده: نضيف الجديد **جنب** القديم → نغيّر n8n → نشيل القديم.
--     في كل خطوة، القيد اللي n8n بيطلبه موجود.
-- ═══════════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────────
-- ٠) فحص مسبق — قراءة بس. لو أي سطر طلع غير المتوقع، **اوقف**.
-- ───────────────────────────────────────────────────────────────────
select
  (select count(*) from public.sales_items where store_name is null or store_name = '')
      as "لازم 0 — مخزن فاضي",
  (select count(*) from (select store_name,bill_no,line_no from public.sales_items
                         group by 1,2,3 having count(*) > 1) x)
      as "لازم 0 — تكرار على المفتاح الجديد",
  (select count(*) from pg_constraint where conname = 'sales_items_store_bill_line_key')
      as "0 = الخطوة ١ ماتعملتش لسه";


-- ───────────────────────────────────────────────────────────────────
-- ١) القيد الجديد **جنب** القديم
-- ───────────────────────────────────────────────────────────────────
-- CONCURRENTLY = مابيقفلش الجدول، فالمزامنة والشاشات شغّالين عادي.
-- ⚠️ CONCURRENTLY مايشتغلش جوّه transaction — شغّل السطر ده **لوحده**.
-- مستحيل يفشل على البيانات الحالية: لو (bill_no, line_no) فريد،
-- يبقى (store_name, bill_no, line_no) فريد تلقائيًا.

create unique index concurrently if not exists sales_items_store_bill_line_idx
  on public.sales_items (store_name, bill_no, line_no);

alter table public.sales_items
  add constraint sales_items_store_bill_line_key
  unique using index sales_items_store_bill_line_idx;


-- ───────────────────────────────────────────────────────────────────
-- ٢) في n8n (يدوي) — وركفلو المبيعات → نود «Upsert Sales Items»
-- ───────────────────────────────────────────────────────────────────
--    Matching Columns:  bill_no, line_no
--                  →    store_name, bill_no, line_no
--
--    احفظ، وشغّل الوركفلو **يدوي مرة**.
--    ⚠️ ماتكملش للخطوة ٣ قبل ما تتأكد إن التشغيل نجح (الفحص تحت).


-- ───────────────────────────────────────────────────────────────────
-- ٣) تحقق إن n8n بيكتب بالمفتاح الجديد
-- ───────────────────────────────────────────────────────────────────
select store_name as المخزن,
       count(*) as صفوف_آخر_ساعة,
       to_char(max(bill_date) at time zone 'Africa/Cairo','MM-DD HH24:MI') as آخر_فاتورة
from public.sales_items
where bill_date > now() - interval '1 hour'
group by 1 order by 1;
-- لازم التلات مخازن يظهروا بصفوف (لو فيه مبيعات في الساعة دي).
-- لو طلع فاضي خالص، شوف n8n: الغالب upsert فشل.


-- ───────────────────────────────────────────────────────────────────
-- ٤) شيل القيد القديم — بعد ما الخطوة ٣ تنجح بس
-- ───────────────────────────────────────────────────────────────────
alter table public.sales_items drop constraint sales_items_bill_no_line_no_key;

select conname as القيود_الفريدة_المتبقية, pg_get_constraintdef(oid) as التعريف
from pg_constraint
where conrelid = 'public.sales_items'::regclass and contype = 'u';
-- المتوقع: sales_items_store_bill_line_key بس.


