/* ============================================================
   «آخر سحب» في شاشة visa كان بيكدب
   ------------------------------------------------------------
   الشاشة كانت بتقول «آخر سحب: ٢١/١٠ ١:٤٦ م» بعد ٣ أيام من السحب
   الناجح — والأرصدة نفسها **كانت متحدّثة فعلًا** (رصيد visa المعمورة
   ٦٢٤,٩٩٣ مقابل ٥٢٨,٤٩٠ يوم ٢١).

   السبب: مهمة `safes` بتعمل upsert على (branch, fcs_id) وأعمدتها
   المختارة مافيهاش `synced_at`. العمود `default now()` بيشتغل عند
   **الإدراج بس**، والصفوف دي عمرها ما بتتدرج تاني — بتتحدّث. فالتاريخ
   اتجمّد عند أول سحب.

   ليه ده خطر مش مجرد شكل: التاريخ ده هو الوحيد اللي بيقول للمستخدم إن
   رقم الخزنة طازج. وهو بيقول «قديم ٣ أيام» وهو مش قديم، فالمستخدم
   يفقد الثقة في رقم صحيح — أو يصدّقه ويقارن أرقام من لحظتين مختلفتين.
   (وده ضلّلني أنا كمان في أول التشخيص.)

   الفرق عن `cashier_transactions`: هناك كل صف جديد بـfh_id جديد
   فبيتدرج والـdefault بيشتغل — عشان كده تاريخها سليم.

   الحل تريجر بدل ما نضيف العمود لجملة الـSELECT: الوقت لازم يكون
   وقت **السيرفر** مش وقت جهاز الصيدلية، والتريجر بيغطي أي مهمة
   مستقبلية تكتب في الجدول من غير ما حد يفتكر.
   ============================================================ */

create or replace function public.touch_synced_at()
returns trigger
language plpgsql
as $$
begin
  new.synced_at := now();
  return new;
end $$;

drop trigger if exists trg_eplus_safes_synced on public.eplus_safes;
create trigger trg_eplus_safes_synced
  before insert or update on public.eplus_safes
  for each row execute function public.touch_synced_at();
