-- التريجر trg_sync_branch_user_to_auth بيزامن الاسم لـauth.users كمان،
-- فالـfull_name اللي في التوكن (اللي بتتنسب بيه الإجراءات زي مراجعة
-- المحاسب والجرد) بيتصلّح مع نفس السطر.
--
-- اتطبّق على السحابة 2026-10-04. مطلوب على السيرفر الذاتي.
