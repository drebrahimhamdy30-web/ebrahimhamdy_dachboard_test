#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════
#  الاستلحاق: خلّي السيرفر مطابق للسحابة، وقول لو مانجحش
# ═══════════════════════════════════════════════════════════════════
#  ليه سكربت واحد مش تلات أوامر:
#
#  الاستلحاق **عمليتين** ولو نسيت التانية تفتكر إنك خلصت:
#    migrate_34  بيجيب الناقص (جداول · دوال · تريجرات · سياسات · فهارس)
#    migrate_35  بيسوّي الصلاحيات و not null
#
#  ومن غير 35، الجرانت يفضل **أوسع** من السحابة — لأن السيرفر الذاتي
#  بيدّي authenticated كل حاجة على أي جدول جديد تلقائيًا، وGRANT بتضيف
#  مابتشيلش. حصلت النهاردة: 34 نجح في ٣٦ بند، والجرانت على الجدولين
#  الجداد فضل ناقص لأن 35 مااشتغلش بعده.
#
#  ═══ ليه ده بيتشغّل كل شوية مش مرة ═══
#  السحابة **هدف متحرّك**. أي جدول أو دالة تتعمل هناك — والأغلب من غير
#  ملف ترحيل — السيرفر يرجع ناقص. «صفر انحراف» مش حالة، ده لحظة.
#  وصلنا لانحراف = ١، وبعد ساعة شغل طلع ٣٥ لأن جدولين جداد اتعملوا
#  على السحابة في الوقت ده.
#
#  الاستعمال (على السيرفر):
#     ./scripts/catchup.sh            # تجربة — بيقول هيعمل إيه وبس
#     ./scripts/catchup.sh --apply    # ينفّذ الاتنين ويتحقّق
#
#  بيرجّع 0 لو الانحراف بقى صفر، و1 لو لسه فيه حاجة — فينفع في الكرون
#  وفي بوابة يوم التحويل.
# ═══════════════════════════════════════════════════════════════════
set -uo pipefail

REPO="${PHALIX_REPO:-/root/phalix-repo}"
COMPOSE_DIR="${PHALIX_COMPOSE_DIR:-/root/supabase-project}"
DB_USER="${PHALIX_DB_USER:-supabase_admin}"
APPLY=0
[ "${1:-}" = "--apply" ] && APPLY=1

if [ -t 1 ]; then G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; B=$'\033[1m'; N=$'\033[0m'
else G=''; Y=''; R=''; B=''; N=''; fi

cd "$COMPOSE_DIR" 2>/dev/null || { echo "${R}✗ مجلد سوبابيز مش موجود: $COMPOSE_DIR${N}"; exit 2; }
CID="$(docker compose ps -q db 2>/dev/null | head -1)"
[ -n "$CID" ] || { echo "${R}✗ حاوية القاعدة مش لاقيها${N}"; exit 2; }

run() {  # $1=ملف  $2=وصف  [$3=apply]
  local f="$REPO/docs/$1" extra=()
  [ -f "$f" ] || { echo "${R}✗ مش لاقي $f${N}"; return 2; }
  [ "${3:-}" = "apply" ] && extra=(-v apply=1)
  printf '\n%s── %s ──%s\n' "$B" "$2" "$N"
  docker exec -i "$CID" psql -U "$DB_USER" -d postgres "${extra[@]}" < "$f"
}

if [ "$APPLY" != 1 ]; then
  run migrate_34_catchup_from_cloud.sql "١/٣ الناقص من السحابة (تجربة)"
  run migrate_35_align_notnull_and_grants.sql "٢/٣ الصلاحيات و not null (تجربة)"
  printf '\n%s(تجربة — مفيش حاجة اتغيّرت)%s\n' "$Y" "$N"
  echo "للتنفيذ: $0 --apply"
  exit 0
fi

run migrate_34_catchup_from_cloud.sql "١/٣ الناقص من السحابة" apply
run migrate_35_align_notnull_and_grants.sql "٢/٣ الصلاحيات و not null" apply

# ── التحقّق: الحارس هو الحكم، مش خرج الترحيلات ────────────────────
printf '\n%s── ٣/٣ التحقّق ──%s\n' "$B" "$N"
OUT="$(docker exec -i "$CID" psql -U "$DB_USER" -d postgres \
       < "$REPO/docs/schema_drift_watch.sql" 2>&1)"
echo "$OUT" | sed -n '/حاجات موجودة على السحابة/,$p'

if echo "$OUT" | grep -q 'مفيش انحراف'; then
  printf '\n%s%s✓ السيرفر مطابق للسحابة.%s\n' "$G" "$B" "$N"
  exit 0
fi

# الحارس بيوقف بخطأ لو مصدره فاضي — ده مش «نضيف»، ده فحص ماحصلش
if echo "$OUT" | grep -qE 'ERROR|مش هحكم على حاجة|عطل في الفلتر'; then
  printf '\n%s%s🔴 الفحص نفسه فشل — مانعرفش الحالة.%s\n' "$R" "$B" "$N"
  echo "$OUT" | grep -E 'ERROR|مش هحكم|عطل' | head -5 | sed 's/^/   /'
  exit 2
fi

printf '\n%s⚠️ لسه فيه انحراف — شوف القايمة فوق.%s\n' "$Y" "$N"
cat <<EOF
  الأسباب المتوقّعة:
    • دالة نوع إرجاعها اتغيّر واتشالت وفشلت تتعمل (شوف خرج ١/٣)
    • حاجة على السحابة مالهاش نظير ينفع يتنقل (view معتمد على حاجة ناقصة)
    • جدول staging اتعمل وقت الفحص — شغّل تاني وشوف لو اختفى
  ${B}ولو اليوم يوم التحويل: ماتحوّلش قبل ما ده يبقى صفر.${N}
EOF
exit 1
